def digest(value):
    return hashlib.sha256(storage.dumps(value).encode()).hexdigest()[:20]


def write_cache(path, value):
    path = Path(path); path.parent.mkdir(parents=True,exist_ok=True)
    temp = path.with_suffix('.tmp')
    with temp.open('wb') as out:
        pickle.dump(value,out,protocol=pickle.HIGHEST_PROTOCOL)
    temp.replace(path)


def read_cache(path):
    # Only load caches generated by this script in your own cache directory.
    with Path(path).open('rb') as src:
        return pickle.load(src)


def load_signature(c):
    keys = ('recordings','groups','groups_by_recording','group_mode','quality',
            'bar_indices','bar_indices_by_recording','rf_sources','processing',
            'rf_recordings_only','rf_min_cells','rf_pixel_rule','rf_scale_by_pixel','rf_surround')
    return digest(dict(version=VERSION,master=storage.fingerprint(c['master_file']),
                       settings={k:c[k] for k in keys}))


def choose_indices(request, available):
    if request == 'all':
        return sorted(set(int(x) for x in available))
    if not isinstance(request,(list,tuple)) or any(int(x)!=x for x in request):
        raise ValueError("Indices/groups must be 'all' or an explicit list of integers")
    return sorted(set(int(x) for x in request).intersection(int(x) for x in available))


def rf_choices(db, c):
    table = db.table('rf_sources')
    chosen = {}
    for recording in db.table('cells').recording.unique():
        if c['recordings'] is not None and recording not in c['recordings']:
            continue
        subset = table[(table.recording==recording)&(table.status=='complete')]
        rule = c.get('rf_pixel_rule', storage.RF_PIXEL_RULE)
        options = [f'rf:{int(r.stimulus_index)}:{r.channel}' for r in subset.itertuples()
                   if storage.rf_allowed(recording, r.channel, rule)]
        if recording in c['rf_sources']:
            value = c['rf_sources'][recording]
            if value is not None and value not in options:
                raise ValueError(f'{recording}: RF_SOURCES must be one of {options}, or None')
            chosen[recording] = value
        elif len(options)>1:
            raise ValueError(f'{recording}: choose one source in RF_SOURCES: {options}')
        else:
            chosen[recording] = options[0] if options else None
    return chosen


def inspect_master(c):
    db = storage.MasterDataset(c['master_file'])
    try:
        stimuli = db.table('stimuli')
        for rec, rows in stimuli.groupby('recording',sort=False):
            groups = sorted(rows.loc[(rows.kind=='raw+QI')&rows.role.isin(FFF),'group_number'].dropna().astype(int).unique())
            bars = rows.loc[(rows.role=='moving_bar')&(rows.status=='complete'),'stimulus_index'].tolist()
            print(f'{rec}: exported FF groups {groups}; moving bars {bars}')
        rf = db.table('rf_sources')
        print('\nRF sources (set an exact context in RF_SOURCES when several exist):')
        for row in rf.itertuples():
            print(f'{row.recording}: rf:{row.stimulus_index}:{row.channel} [{row.status}]')
        return dict(stimuli=stimuli,rf_sources=rf)
    finally:
        db.close()


def select_rows(db, c):
    """Cell-level eligibility ONLY; low-quality measured features remain usable."""
    q = c['quality']
    if q['mode'] not in ('fff_or_rf','fff_and_rf','fff_only','rf_only','none') or q['fff_rule'] not in ('any','all'):
        raise ValueError('Invalid quality rule')
    if q.get('rf_edge') not in (None,'drop_rf','drop_cell'):
        raise ValueError("QUALITY['rf_edge'] must be None, 'drop_rf' or 'drop_cell'")
    if c['group_mode'] not in ('average','separate'):
        raise ValueError("group_mode must be 'average' or 'separate'")
    obs = db.observations()
    cells = db.table('cells')
    if c['recordings'] is not None:
        unknown = set(c['recordings'])-set(cells.recording)
        if unknown:
            raise ValueError(f'Recordings not in master: {sorted(unknown)}')
        cells = cells[cells.recording.isin(c['recordings'])]
    sources = rf_choices(db,c)
    rf = db.rf_scalars()
    if len(rf):
        rf = rf[[sources.get(r.recording)==r.context for r in rf.itertuples()]]
        rf_lookup = {(r['recording'],int(r['cell_index'])):r for r in rf.to_dict('records')}
    else:
        rf_lookup = {}
    if c.get('rf_recordings_only'):
        # Keep only recordings with at least rf_min_cells cells whose RF quality
        # exceeds quality['rf_threshold'] (same rule that defines an eligible RF).
        eligible = {}
        for (rec, _), values in rf_lookup.items():
            qi = values.get('rf_quality', np.nan)
            if np.isfinite(qi) and qi > q['rf_threshold']:
                eligible[rec] = eligible.get(rec, 0) + 1
        keep_recordings = {r for r, n in eligible.items() if n >= c['rf_min_cells']}
        dropped = sorted(set(cells.recording) - keep_recordings)
        minimum = c['rf_min_cells']
        print(f'RF-recordings-only: keeping {len(keep_recordings)} recordings; '
              f'dropping {len(dropped)} without >= {minimum} eligible RF cells: {dropped}', flush=True)
        cells = cells[cells.recording.isin(keep_recordings)]
        if cells.empty:
            raise ValueError('No recordings have eligible receptive fields at this rf_threshold / rf_min_cells')
    inventory = db.table('stimuli')
    selected_groups = {}
    for rec in cells.recording.unique():
        available = inventory.loc[(inventory.recording==rec)&inventory.role.isin(FFF)&(inventory.kind=='raw+QI'),'group_number'].dropna().astype(int)
        request = c['groups_by_recording'].get(rec,c['groups'])
        selected_groups[rec] = choose_indices(request,available)
        if request != 'all' and set(request)-set(available):
            print(f'{rec}: unavailable requested FF groups {sorted(set(request)-set(available))}; no replacement group used.',flush=True)
    selected_obs = obs[[r.role in FFF and pd.notna(r.group_number) and int(r.group_number) in selected_groups.get(r.recording,[]) for r in obs.itertuples()]]
    lookup = {(r,int(cell)):frame for (r,cell),frame in selected_obs.groupby(['recording','cell_index'])}
    output, audit, group_audit = [], [], []
    for cell in cells.itertuples():
        key = (cell.recording,int(cell.cell_index))
        frame = lookup.get(key,selected_obs.iloc[:0])
        group_list, passing = [], []
        for group, g in frame.groupby('group_number'):
            group = int(group)
            if g.role.duplicated().any():
                raise ValueError(f'Duplicate role in {key}, group {group}')
            qis = {role:float(g.loc[g.role==role,'qi'].iloc[0]) if (g.role==role).any() and pd.notna(g.loc[g.role==role,'qi'].iloc[0]) else np.nan for role in FFF}
            flags = [np.isfinite(qis[r]) and qis[r]>q['fff_threshold'] for r in FFF]
            passed = any(flags) if q['fff_rule']=='any' else all(flags)
            group_list.append(group)
            if passed: passing.append(group)
            group_audit.append(dict(recording=cell.recording,cell_index=int(cell.cell_index),group_number=group,
                                    **{f'{r}_qi':qis[r] for r in FFF},passes_fff=passed))
        rf_values = rf_lookup.get(key,{})
        rf_qi = rf_values.get('rf_quality',np.nan)
        rf_pass = bool(np.isfinite(rf_qi) and rf_qi>q['rf_threshold'])
        edge = rf_values.get('rf_edge_margin_um',np.nan)
        rf_at_edge = bool(np.isfinite(edge) and edge<=q.get('rf_edge_margin_um',0.))
        ff_pass = bool(passing)
        keep = {'fff_or_rf':ff_pass or rf_pass,'fff_and_rf':ff_pass and rf_pass,
                'fff_only':ff_pass,'rf_only':rf_pass,'none':True}[q['mode']]
        dropped_edge = bool(keep and rf_at_edge and q.get('rf_edge')=='drop_cell')
        if dropped_edge: keep = False
        audit.append(dict(recording=cell.recording,cell_index=int(cell.cell_index),cell_uid=cell.cell_uid,
                          selected_groups=group_list,passing_groups=passing,fff_pass=ff_pass,
                          rf_quality=rf_qi,rf_pass=rf_pass,rf_edge_margin_um=edge,rf_at_edge=rf_at_edge,dropped_rf_edge=dropped_edge,included=keep))
        if not keep: continue
        # Separate mode still uses CELL-level eligibility: no failing selected
        # group is removed when another selected group or RF rescues the cell.
        observations = [group_list] if c['group_mode']=='average' else [[g] for g in group_list] or [[]]
        for groups in observations:
            record = dict(recording=cell.recording,cell_index=int(cell.cell_index),cell_uid=cell.cell_uid,
                          groups=groups,fff_pass=ff_pass,rf_pass=rf_pass,rf_quality=rf_qi,rf_at_edge=rf_at_edge,
                          rf_context=sources.get(cell.recording),
                          observation_uid=cell.cell_uid+(':average' if c['group_mode']=='average' else ':group_'+str(groups[0]) if groups else ':no_FF'))
            output.append(record)
    return dict(rows=pd.DataFrame(output),audit=pd.DataFrame(audit),group_audit=pd.DataFrame(group_audit),
                observations=obs,rf_lookup=rf_lookup,selected_groups=selected_groups)


def smooth(times, grid, bandwidth):
    values = np.zeros(len(grid))
    for start in range(0,len(times),1024):
        z = (grid[:,None]-times[None,start:start+1024])/bandwidth
        values += np.exp(-.5*z*z).sum(axis=1)
    return values/(bandwidth*np.sqrt(2*np.pi))


def response(db, rec, cell, index, role, p):
    raw = db.spikes(rec,cell,index)
    meta = db.stimulus_metadata(rec,index)
    rel = np.asarray(meta['trigger_fr_relative'],dtype=np.int64)
    logic = int(meta['stimulus_repeat_logic']); fs = float(meta['sampling_freq'])
    if logic<1 or len(rel)<2 or np.any(np.diff(rel)<=0) or not np.isfinite(fs) or fs<=0:
        raise ValueError('Invalid timing metadata')
    count = min(int(meta['nr_repeats']),(len(rel)-1)//logic)
    if role=='moving_bar' and logic!=p['frames_per_direction']*p['directions']:
        raise ValueError('Moving-bar trigger geometry is not 300 frames x 8 directions')
    absolute = int(meta['begin_fr'])+rel
    if not meta.get('inferred_final_trigger_count',0):
        while count and absolute[count*logic]>int(meta['end_fr']): count-=1
    if count<1: raise ValueError('No complete repeat boundaries')
    trials = []
    for r in range(count):
        begin,end = absolute[r*logic],absolute[(r+1)*logic]
        events = raw[(raw>=begin)&(raw<end)]
        if role=='moving_bar':
            edges = absolute[r*logic:(r+1)*logic+1:p['frames_per_direction']]
            direction = np.searchsorted(edges,events,side='right')-1
            times = (direction+(events-edges[direction])/np.diff(edges)[direction])*p['direction_duration_s']
            times = storage.bar_times_to_door(times, rec, p['direction_duration_s'])
        else:
            times = (events-begin)/fs
        trials.append(times[(times>=0)&(times<p['durations'][role])])
    times = np.concatenate(trials)
    grid = np.linspace(0,p['durations'][role],p['samples'])
    density = smooth(times,grid,p['bandwidth_s'])
    result = dict(pdf=density/len(times) if len(times) else density.copy(),rate=density/count,
                  repeats=count,status='ok',spikes_used=len(times))
    if role=='moving_bar':
        duration=p['direction_duration_s']; width=p['selectivity_bin_s']
        bins = np.r_[np.arange(0,duration,width),duration]
        response_values=[]
        for d in range(p['directions']):
            local=times[(times>=d*duration)&(times<(d+1)*duration)]-d*duration
            response_values.append(np.max(np.histogram(local,bins)[0]/(np.diff(bins)*count)))
        result['direction_response']=np.asarray(response_values)
    return result


def selectivity(responses, directions):
    if not np.isfinite(responses).all() or np.sum(responses)<=0:
        return np.nan,np.nan
    angles=np.asarray(directions,float)
    preferred=int(np.argmax(responses))
    delta=np.abs((angles-angles[preferred]-180+180)%360-180)
    opposite=int(np.argmin(delta))
    a,b=responses[[preferred,opposite]]
    dsi=(a-b)/(a+b) if a+b>0 else np.nan
    osi=np.abs(np.sum(responses*np.exp(2j*np.deg2rad(angles))))/np.sum(responses)
    return float(dsi),float(osi)


def bar_reference_time(local, v, base, p):
    """Time within one bar direction that is moved to peak_target_s.

    'peak'  : the single highest point (original method). In ON-OFF cells the OFF
              peak (~0.9 s after ON) is the bigger one in 35-56 % of responses, so
              cells were aligned on ON or OFF at random and cluster averages showed
              three peaks (2.5 - 0.9, 2.5, 2.5 + 0.9 s).
    'first' : the first clear peak, i.e. roughly when the bar's leading edge reaches
              the cell. A peak is clear if its prominence is at least
              bar_align_fraction * (highest point - baseline). ON-OFF cells then
              always have ON at peak_target_s and OFF after it. On the 8 example
              recordings (same clusters) this halved three-peak cluster averages
              (14 -> 7 of 128) and gave consistent ON-OFF pairs (2-peak 47 -> 82).
    """
    method=p.get('bar_align_method','peak')
    if method=='peak':
        return local[np.argmax(v)]
    if method=='first':
        from scipy.signal import find_peaks
        peaks,_=find_peaks(v,prominence=p.get('bar_align_fraction',.4)*(v.max()-base))
        return local[peaks[0]] if len(peaks) else local[np.argmax(v)]
    raise ValueError(f"Unknown bar_align_method {method!r}: use 'first' or 'peak'")


def align_curve(values, grid, p):
    out=values.copy(); duration=p['direction_duration_s']
    for d in range(p['directions']):
        mask=(grid>=d*duration)&(grid<(d+1)*duration)
        if d==p['directions']-1: mask[-1]=True
        local=grid[mask]-d*duration; v=values[mask]
        if len(v)<2 or not np.isfinite(v).all() or np.ptp(v)<1e-12: continue
        base=np.percentile(v,p['baseline_percentile'])
        shift=p['peak_target_s']-bar_reference_time(local,v,base,p)
        out[mask]=np.interp(local-shift,local,v,left=base,right=base)
    return out


def read_sta(db, rec, cell, context, p):
    grid=np.linspace(*p['sta_time_range_s'],p['sta_samples'])
    try:
        item=db.feature(rec,cell,context,'temporal_sta')
    except KeyError:
        return np.full(len(grid),np.nan),'missing STA'
    if item['values'] is None: return np.full(len(grid),np.nan),'missing STA'
    y=np.asarray(item['values'],float); meta=item['metadata']
    dims=meta.get('dims',[])
    if y.ndim!=1 or len(dims)!=1 or dims[0] not in meta.get('coordinates',{}):
        return np.full(len(grid),np.nan),'STA lacks one time coordinate'
    coord=meta['coordinates'][dims[0]]
    x=np.asarray(coord['values'],float)
    unit=str(coord.get('attrs',{}).get('units',p['sta_time_unit_if_absent'])).lower()
    scales={'ms':.001,'millisecond':.001,'milliseconds':.001,'s':1.,'second':1.,'seconds':1.}
    if unit not in scales: raise ValueError(f'Unsupported STA time unit {unit!r} in {rec}')
    x=x*scales[unit]
    valid=np.isfinite(x)&np.isfinite(y)
    if valid.sum()<2: return np.full(len(grid),np.nan),'missing STA samples'
    # Trim only external coordinate padding, never bridge an internal NaN gap.
    lo,hi=np.flatnonzero(valid)[[0,-1]]
    x,y=x[lo:hi+1],y[lo:hi+1]
    if not np.isfinite(x).all() or np.any(np.diff(x)<=0) or not np.isfinite(y).all():
        return np.full(len(grid),np.nan),'invalid STA / internal gap'
    if grid[0]<x[0]-1e-9 or grid[-1]>x[-1]+1e-9:
        return np.full(len(grid),np.nan),'STA does not cover requested time range'
    return np.interp(grid,x,y),'ok'


def noise_pixel_size(context):
    """'rf:6:12px_20Hz_shuffle' -> 12 (None if unknown)."""
    m = re.search(r'(\d+)px', str(context)) if isinstance(context, str) else None
    return int(m.group(1)) if m else None


def adjust_rf_sizes(extras, rows, c):
    """Reversible corrections of RF sizes, in place (settings in clustering_master_main.py).

    rf_scale_by_pixel {pixel size: factor}: lengths of that noise are multiplied by the factor,
        so centre/surround AREAS by factor**2 (e.g. {12: 1.25}: 12 px noise really 5 um/px, not 4).
        Shape (elongation) and time course are unaffected.
    rf_surround: 'as_is' | 'normalise_by_pixel' (each pixel size's surround sizes divided by
        that group's median and multiplied by the median of the largest group, so 'large
        surround' means large for that noise) | 'drop' (surround size left out, all missing).
    """
    pixel = np.array([noise_pixel_size(x) or -1 for x in rows['rf_context']])
    for size, factor in (c.get('rf_scale_by_pixel') or {}).items():
        hit = pixel == int(size)
        for name in ('center_size_mm2', 'surround_size_mm2'):
            extras[name][hit] *= float(factor) ** 2
        if hit.any():
            print(f'RF sizes of {int(hit.sum())} cells with {size} px noise scaled by {float(factor):g} '
                  f'(areas x {float(factor) ** 2:g}).', flush=True)
    mode = c.get('rf_surround') or 'as_is'
    if mode not in ('as_is', 'normalise_by_pixel', 'drop'):
        raise ValueError("RF_SURROUND must be 'as_is', 'normalise_by_pixel' or 'drop'")
    sur = extras['surround_size_mm2'][:, 0]
    if mode == 'drop':
        sur[:] = np.nan
        print('RF surround size left out (RF_SURROUND = drop).', flush=True)
    elif mode == 'normalise_by_pixel':
        groups = [g for g in np.unique(pixel) if g > 0 and np.isfinite(sur[pixel == g]).any()]
        if len(groups) > 1:
            ref = max(groups, key=lambda g: np.isfinite(sur[pixel == g]).sum())
            ref_median = np.nanmedian(sur[pixel == ref])
            for g in groups:
                med = np.nanmedian(sur[pixel == g])
                if med > 0:
                    sur[pixel == g] *= ref_median / med
            print(f'RF surround sizes normalised within each noise pixel size (to the {ref} px median).', flush=True)


def load_data(c, force=False):
    p=c['processing']
    if p['bandwidth_s']<=0 or p['samples']<20 or not 0<p['selectivity_bin_s']<=p['direction_duration_s']:
        raise ValueError('Invalid smoothing/bin settings')
    signature=load_signature(c); root=Path(c['cache_dir']); root.mkdir(parents=True,exist_ok=True)
    target=root/f'data_{signature}.pkl'
    if target.exists() and not force:
        print('Loaded saved selected responses; no spike processing.',flush=True)
        return read_cache(target)
    db=storage.MasterDataset(c['master_file'])
    try:
        selection=select_rows(db,c); rows=selection['rows']
        selection['audit'].to_csv(root/f'selection_{signature}.csv',index=False)
        selection['group_audit'].to_csv(root/f'group_qi_{signature}.csv',index=False)
        if rows.empty: raise ValueError('No cells pass the requested group/RF quality rule. See selection CSV.')
        print(f"Retained {rows.cell_uid.nunique()} cells / {len(rows)} observations. Moving-bar quality is ignored.",flush=True)
        audit=selection['audit']
        if 'rf_at_edge' in audit and audit.rf_at_edge.any():
            action=c['quality'].get('rf_edge')
            n_edge=int(audit.dropped_rf_edge.sum()) if action=='drop_cell' else int(audit.rf_at_edge[audit.included].sum())
            text={'drop_rf':'kept, RF shape features left out','drop_cell':'left out completely',None:'RF used as is'}[action]
            print(f"RF cut off by the stimulus edge: {n_edge} selected cells ({text}).",flush=True)
        # Bank is independent of selected groups and feature switches.
        response_settings={k:p[k] for k in ('bandwidth_s','samples','durations','frames_per_direction',
                           'directions','direction_duration_s','selectivity_bin_s')}
        bank_key=digest(dict(master=storage.fingerprint(c['master_file']),processing=response_settings,version=VERSION))
        bank_path=root/f'response_bank_{bank_key}.pkl'
        bank=read_cache(bank_path) if bank_path.exists() and not force else {}
        grids={r:np.linspace(0,p['durations'][r],p['samples']) for r in RESPONSES}
        data={r:dict(grid=grids[r],pdf=np.full((len(rows),p['samples']),np.nan),rate=np.full((len(rows),p['samples']),np.nan)) for r in RESPONSES}
        extras={k:np.full((len(rows),p['sta_samples'] if k=='temporal_sta' else 1),np.nan) for k in EXTRAS}
        errors=[]; obs_lookup={(rec,int(cell)):g for (rec,cell),g in selection['observations'].groupby(['recording','cell_index'])}
        last_rec=None
        for i,row in enumerate(rows.itertuples()):
            if row.recording!=last_rec:
                if last_rec is not None: write_cache(bank_path,bank)
                print(f'Preparing {row.recording} ...',flush=True); last_rec=row.recording
            obs=obs_lookup.get((row.recording,row.cell_index),selection['observations'].iloc[:0])
            for role in RESPONSES:
                possible=obs[obs.role==role]
                if role in FFF:
                    possible=possible[possible.group_number.isin(row.groups)]
                else:
                    requested=c['bar_indices_by_recording'].get(row.recording,c['bar_indices'])
                    indices=choose_indices(requested,possible.stimulus_index)
                    possible=possible[possible.stimulus_index.isin(indices)]
                values=[]
                for source in possible.itertuples():
                    key=(row.recording,int(row.cell_index),int(source.stimulus_index))
                    if key not in bank:
                        try: bank[key]=response(db,*key,role,p)
                        except (ValueError,KeyError,TypeError) as exc:
                            bank[key]=dict(status=str(exc))
                    item=bank[key]
                    if item['status']=='ok': values.append(item)
                    else: errors.append(dict(recording=row.recording,cell_index=row.cell_index,stimulus_index=source.stimulus_index,error=item['status']))
                if values:
                    # Equal weight per selected presentation/group, including low QI.
                    for field in ('pdf','rate'):
                        curve=np.mean([v[field] for v in values],axis=0)
                        if role=='moving_bar' and p['bar_peak_align']:
                            curve=align_curve(curve,grids[role],p)
                        data[role][field][i]=curve
                    if role=='moving_bar':
                        dsi,osi=selectivity(np.mean([v['direction_response'] for v in values],axis=0),p['directions_deg'])
                        extras['DSI'][i,0]=dsi; extras['OSI'][i,0]=osi
            rf=selection['rf_lookup'].get((row.recording,int(row.cell_index)),{})
            if row.rf_at_edge and c['quality'].get('rf_edge')=='drop_rf':
                rf={}  # RF cut off by the stimulus edge: shape features left missing (temporal STA kept)
            for name in ('center_size_mm2','surround_size_mm2','elongation'):
                value=rf.get(name,np.nan)
                if np.isfinite(value) and (value>=0 if name=='surround_size_mm2' else value>=1 if name=='elongation' else value>0):
                    extras[name][i,0]=value
            angle=rf.get('orientation_deg',np.nan)
            if np.isfinite(angle):
                unit=p['orientation_unit_if_absent']
                try:
                    item=db.feature(row.recording,row.cell_index,row.rf_context,'orientation_deg')
                    unit=item['metadata'].get('attrs',{}).get('units',unit)
                except KeyError: pass
                if str(unit).lower() in ('radian','radians','rad'): angle=np.rad2deg(angle)
                elif str(unit).lower() not in ('degree','degrees','deg'):
                    errors.append(dict(recording=row.recording,cell_index=row.cell_index,stimulus_index=None,error=f'Unsupported RF angle unit {unit}'))
                    angle=np.nan
                extras['orientation'][i,0]=angle%180
            if row.rf_context:
                try:
                    extras['temporal_sta'][i],status=read_sta(db,row.recording,row.cell_index,row.rf_context,p)
                except (ValueError,TypeError) as exc:
                    status=str(exc)
                if status!='ok': errors.append(dict(recording=row.recording,cell_index=row.cell_index,stimulus_index=None,error=status))
            if (i+1)%100==0: print(f'  {i+1}/{len(rows)} observations',flush=True)
        write_cache(bank_path,bank)
        adjust_rf_sizes(extras,rows,c)
        settings_used={k:c.get(k) for k in ('recordings','groups','groups_by_recording','group_mode','quality','bar_indices',
                       'bar_indices_by_recording','rf_sources','rf_pixel_rule','rf_recordings_only','rf_min_cells',
                       'rf_scale_by_pixel','rf_surround','exclude_missing')}
        settings_used['master_file']=str(c['master_file']); settings_used['master_revision']=storage.fingerprint(c['master_file'])
        dataset=dict(signature=signature,rf_scale_by_pixel=dict(c.get('rf_scale_by_pixel') or {}),settings_used=settings_used,group_mode=c['group_mode'],rows=rows,responses=data,extras=extras,selection_audit=selection['audit'],
                     group_audit=selection['group_audit'],processing=p,errors=pd.DataFrame(errors),
                     sta_grid=np.linspace(*p['sta_time_range_s'],p['sta_samples']))
        write_cache(target,dataset)
        dataset['errors'].to_csv(root/f'processing_issues_{signature}.csv',index=False)
        print(f'Saved selected responses: {target}',flush=True)
        return dataset
    finally: db.close()


def make_features(dataset,c):
    enabled=[k for k,v in c['features'].items() if v]
    if not enabled or set(enabled)-set(RESPONSES+EXTRAS): raise ValueError('Choose valid enabled features')
    if not 0<c['analysis']['pca_variance']<=1: raise ValueError('PCA variance must be in (0,1]')
    n=len(dataset['rows']); availability={}
    for name in enabled:
        matrix=dataset['responses'][name]['pdf'] if name in RESPONSES else dataset['extras'][name]
        availability[name]=np.isfinite(matrix).all(axis=1)
    availability=pd.DataFrame(availability)
    retained=availability.all(axis=1).to_numpy() if c['exclude_missing'] else np.ones(n,bool)
    if retained.sum()<2: raise ValueError('Fewer than two observations remain after missing-feature selection')
    pieces=[]; report=[]; models=[]
    for name in enabled:
        if name in RESPONSES:
            matrix=dataset['responses'][name]['pdf']; grid=dataset['responses'][name]['grid']
            segments=1 if name=='chirp' else 8 if name in ('scf','moving_bar') else 10
            width=dataset['processing']['direction_duration_s'] if name=='moving_bar' else 4.
            masks=[np.ones(len(grid),bool)] if segments==1 else [(grid>=i*width)&(grid<(i+1)*width) for i in range(segments)]
            masks[-1][-1]=True
        else:
            matrix=dataset['extras'][name]
            if name=='orientation':
                radians=np.deg2rad(matrix[:,0]*2)
                matrix=np.column_stack((np.cos(radians),np.sin(radians)))
            masks=[np.ones(matrix.shape[1],bool)]
        for seg,mask in enumerate(masks):
            block=matrix[:,mask]
            observed=np.isfinite(block).all(axis=1)&retained
            weight=float(c['analysis'].get('feature_weights',{}).get(name,1.))
            if not np.isfinite(weight) or weight<=0: raise ValueError('Feature weights must be positive')
            scores=np.empty((n,0)); variance=0.; model={}
            if observed.sum()>=2:
                center=block[observed].mean(axis=0); centered=block[observed]-center
                if name in RESPONSES or name=='temporal_sta':
                    _,s,vt=np.linalg.svd(centered,full_matrices=False)
                    if (s*s).sum()>1e-25:
                        ratio=s*s/(s*s).sum(); number=min(len(s),np.searchsorted(ratio.cumsum(),c['analysis']['pca_variance'])+1)
                        basis=vt[:number]; variance=float(ratio[:number].sum())
                        scores=np.full((n,number),np.nan); scores[observed]=centered@basis.T
                        model=dict(center=center,basis=basis)
                elif np.var(centered,axis=0).sum()>1e-25:
                    scores=np.full((n,centered.shape[1]),np.nan); scores[observed]=centered
                    variance=1.; model=dict(center=center,basis=None)
            if scores.shape[1]:
                pieces.append(dict(name=name,segment=seg,scores=scores,weight=weight))
                models.append(dict(name=name,segment=seg,mask=mask,**model))
            report.append(dict(feature=name,segment=seg+1,components=scores.shape[1],variance_retained=variance,
                               observed_cells=int(observed.sum()),note='' if scores.shape[1] else 'constant or fewer than 2 available observations'))
    scales=[np.nanstd(p['scores'],axis=0) for p in pieces if p['name'] in RESPONSES]
    scale_array=np.concatenate(scales) if scales else np.array([1.])
    reference=np.median(scale_array[scale_array>1e-12]) if np.any(scale_array>1e-12) else 1.
    for part in pieces:
        scale=1.  # data scale only; weights act on the likelihood (column_weights), not here
        if part['name'] in EXTRAS:
            sd=np.sqrt(np.nansum(np.nanvar(part['scores'],axis=0)))
            scale*=reference/sd
        part['scores']*=scale
        part['scale']=scale
    if not pieces: raise ValueError('No variable enabled features are available; inspect availability and STA time range')
    x=np.hstack([p['scores'] for p in pieces])
    x[~retained]=np.nan
    column_weights=likelihood_weights(pieces,c['analysis'])
    return dict(x=x,availability=availability,retained=retained,report=pd.DataFrame(report),models=models,
                column_blocks=[(p['name'],p['segment'],p['scores'].shape[1],p['scale']) for p in pieces],
                column_weights=column_weights)


RF_GROUP = ('center_size_mm2','surround_size_mm2','elongation','orientation','temporal_sta')


def likelihood_weights(pieces,analysis):
    """How much each column counts when cells are assigned to clusters (weighted likelihood).

    Every column (one PCA component of a response, or one RF number) starts at 1, times
    feature_weights[name]. If analysis['rf_share'] is set (0-1), the RF columns (RF_GROUP)
    are rescaled to that share of the total weight and all other columns (flash, steps,
    chirp, moving bar, DSI, OSI) to the rest; the average column weight stays 1.
    Rescaling the data cannot do this: each cluster fits its own spread per column, so a
    column's influence does not depend on its scale, only on these weights.
    """
    w=np.concatenate([np.full(p['scores'].shape[1],p['weight']) for p in pieces])
    is_rf=np.concatenate([np.full(p['scores'].shape[1],p['name'] in RF_GROUP) for p in pieces])
    share=analysis.get('rf_share')
    if share is not None:
        if not 0<share<1: raise ValueError('rf_share must be between 0 and 1 (or None)')
        if not is_rf.any() or is_rf.all(): raise ValueError('rf_share needs both RF and response features enabled')
        total=w.sum()
        w=np.where(is_rf,w*share*total/w[is_rf].sum(),w*(1-share)*total/w[~is_rf].sum())
    return w


def log_probabilities(x,means,variances,weights,column_weights=None):
    """Marginal diagonal-Gaussian density over OBSERVED coordinates only; each column's
    log-density is multiplied by its weight (weighted likelihood; all 1 = ordinary GMM)."""
    observed=np.isfinite(x); values=np.where(observed,x,0.)
    cw=np.ones(x.shape[1]) if column_weights is None else np.asarray(column_weights,float)
    terms=[]
    for mean,var,weight in zip(means,variances,weights):
        contribution=cw*np.where(observed,np.log(2*np.pi*var)+(values-mean)**2/var,0.)
        terms.append(np.log(max(weight,1e-300))-.5*contribution.sum(axis=1))
    logp=np.column_stack(terms)
    maximum=logp.max(axis=1)
    normaliser=maximum+np.log(np.exp(logp-maximum[:,None]).sum(axis=1))
    return logp-normaliser[:,None],normaliser


def fit_mixture(x,k,covariance,settings,seed,column_weights=None):
    """EM with observed-data likelihood; missing entries never become measurements.

    Model centres are initialised from marginal population statistics plus random
    jitter. M-steps use only observed values for each dimension. Variance floor
    applies in globally standardised coordinates. No mean-filled PCA or inputs.
    """
    n,d=x.shape; rng=np.random.default_rng(seed)
    mask=np.isfinite(x); values=np.where(mask,x,0.)
    mean0=np.nanmean(x,axis=0); var0=np.maximum(np.nanvar(x,axis=0),settings['reg_covar'])
    means=mean0+rng.normal(size=(k,d))*np.sqrt(var0)*.5
    variances=np.tile(var0,(k,1)); weights=np.full(k,1/k)
    previous=-np.inf; converged=False
    for iteration in range(settings['max_iterations']):
        logr,ll=log_probabilities(x,means,variances,weights,column_weights)
        likelihood=ll.sum()
        if np.isfinite(previous) and abs(likelihood-previous)/n < settings['tolerance']:
            converged=True; break
        previous=likelihood
        resp=np.exp(logr); weights=np.maximum(resp.mean(axis=0),1e-12); weights/=weights.sum()
        denominator=resp.T@mask.astype(float)
        numerator=resp.T@values
        means=np.divide(numerator,denominator,out=means.copy(),where=denominator>1e-12)
        squared=resp.T@(values*values)-2*means*numerator+means*means*denominator
        squared=np.maximum(squared,0.)
        if covariance=='tied_diag':
            common=np.divide(squared.sum(axis=0),denominator.sum(axis=0))
            variances=np.tile(np.maximum(common,settings['reg_covar']),(k,1))
        else:
            variances=np.divide(squared,denominator,out=variances.copy(),where=denominator>1e-12)
            variances=np.maximum(variances,settings['reg_covar'])
    logr,ll=log_probabilities(x,means,variances,weights,column_weights)
    params=(k-1)+k*d+(d if covariance=='tied_diag' else k*d)
    return dict(means=means,variances=variances,weights=weights,log_likelihood=float(ll.sum()),
                bic=float(-2*ll.sum()+params*np.log(n)),converged=converged,iterations=iteration+1,
                covariance=covariance,k=k,posterior=np.exp(logr))


def cluster(c,dataset=None,force=False):
    if dataset is None: dataset=load_data(c)
    if dataset['signature']!=load_signature(c): raise ValueError('Selection/processing changed: call run.load_data() first; existing response bank is reused')
    key=digest(dict(data=dataset['signature'],features=c['features'],exclude_missing=c['exclude_missing'],analysis=c['analysis'],version=VERSION))
    root=Path(c['cache_dir']); target=root/f'fit_{key}.pkl'
    if target.exists() and not force:
        print('Loaded saved clustering; no refit.',flush=True); return read_cache(target)
    features=make_features(dataset,c); x=features['x']
    fitted=features['retained']&np.isfinite(x).any(axis=1)
    if fitted.sum()<2: raise ValueError('Fewer than two observations have usable variable features')
    # One GLOBAL scale for numeric stability, preserving relative feature weights.
    global_scale=float(np.sqrt(np.nanmean(np.nanvar(x[fitted],axis=0))))
    xf=x[fitted]/global_scale
    settings=c['analysis']
    if any(v not in ('diag','tied_diag') for v in settings['covariance_types']):
        raise ValueError('Available-feature mixtures support diag and tied_diag covariance')
    if settings['n_initialisations']<1 or settings['max_iterations']<1 or settings['reg_covar']<=0:
        raise ValueError('Invalid mixture settings')
    counts=[int(k) for k in settings['cluster_counts'] if int(k)==k and 1<=k<=fitted.sum()]
    best=None; candidates=[]
    for covariance in settings['covariance_types']:
        for k in counts:
            winner=None
            for start in range(settings['n_initialisations']):
                model=fit_mixture(xf,k,covariance,settings,settings['random_seed']+1009*k+start,features['column_weights'])
                if winner is None or (model['converged'] and not winner['converged']) or (model['converged']==winner['converged'] and model['bic']<winner['bic']): winner=model
            candidates.append({key:winner[key] for key in ('k','covariance','bic','converged','iterations')})
            print(f"K={k}, {covariance}: BIC {winner['bic']:.1f}; converged={winner['converged']}",flush=True)
            if winner['converged'] and (best is None or winner['bic']<best['bic']): best=winner
    if best is None: raise ValueError('No converged fit; increase max_iterations. No unconverged model selected.')
    labels=np.full(len(x),-1,int); confidence=np.full(len(x),np.nan)
    labels[fitted]=best['posterior'].argmax(axis=1); confidence[fitted]=best['posterior'].max(axis=1)
    # Stable display numbering by number of UNIQUE cells, not separate-group rows.
    unique_counts={k:dataset['rows'].loc[labels==k,'cell_uid'].nunique() for k in np.unique(labels[labels>=0])}
    mapping={k:i+1 for i,k in enumerate(sorted(unique_counts,key=lambda k:-unique_counts[k]))}
    labels=np.array([mapping.get(k,-1) for k in labels])
    assignments=dataset['rows'].copy(); assignments['cluster']=labels
    assignments['posterior_max']=confidence; assignments['observed_dimensions']=np.isfinite(x).sum(axis=1)
    assignments['status']=np.where(~features['retained'],'excluded_missing',np.where(fitted,'clustered','unassigned_no_variable_features'))
    for name in features['availability']: assignments['available_'+name]=features['availability'][name].to_numpy()
    assignments.to_csv(root/f'assignments_{key}.csv',index=False)
    support=pd.DataFrame(np.isfinite(x).astype(int)).groupby(labels).sum()
    support.index.name='cluster'
    support.to_csv(root/f'feature_support_{key}.csv')
    result=dict(key=key,data_signature=dataset['signature'],assignments=assignments,features=features,
                candidates=pd.DataFrame(candidates),model=best,global_scale=global_scale,
                label_mapping=mapping,settings=c['analysis'],enabled=c['features'])
    write_cache(target,result)
    print(f"Saved fit/assignments. {fitted.sum()} rows clustered; {(~fitted).sum()} retained in audit without a cluster.",flush=True)
    return result


def mean_sem(matrix):
    valid=np.isfinite(matrix); n=valid.sum(axis=0)
    mean=np.divide(np.nansum(matrix,axis=0),n,out=np.full(matrix.shape[1],np.nan),where=n>0)
    ss=np.nansum((matrix-mean)**2,axis=0)
    sem=np.sqrt(np.divide(ss,n*(n-1),out=np.zeros_like(mean),where=n>1))
    return mean,sem


