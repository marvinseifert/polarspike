def quality_histogram_values(dataset):
    """Use only groups contributing to each row; RF is the selected source's QI.

    Multiple-group rows use the maximum per-stimulus QI over their selected groups.
    This is a display summary, not a new QI for an averaged response.
    """
    rows=dataset['rows']; table=dataset['group_audit']
    values={f'{r}_QI':np.full((len(rows),1),np.nan) for r in FFF}
    values['RF_quality']=np.asarray(rows.rf_quality,dtype=float).reshape(-1,1)
    lookup={}
    if len(table):
        lookup={(rec,int(cell)):g for (rec,cell),g in table.groupby(['recording','cell_index'])}
    for i,row in enumerate(rows.itertuples()):
        g=lookup.get((row.recording,int(row.cell_index)))
        if g is None: continue
        g=g[g.group_number.isin(row.groups)]
        for role in FFF:
            a=g[f'{role}_qi'].to_numpy(float)
            a=a[np.isfinite(a)]
            if len(a): values[f'{role}_QI'][i,0]=a.max()
    return values


def histogram_axes(dataset, assignments, enabled, options):
    """One range/bin grid per feature, across retained AND small-cluster pages."""
    shared=options.get('histogram_shared_x',True)
    overrides=options.get('histogram_xlim',{})
    count=options.get('histogram_bins',12)
    if int(count)!=count or count<1:
        raise ValueError('histogram_bins must be a positive integer')
    clustered=assignments.cluster.to_numpy()>0
    specifications={}
    for name in enabled:
        if name in RESPONSES or name=='temporal_sta': continue
        limits=overrides.get(name)
        if limits is None and name in ('DSI','OSI','scf_QI','csteps_QI','chirp_QI'): limits=(0.,1.)
        if limits is None and name=='orientation': limits=(0.,180.)
        if limits is None and shared:
            values=np.asarray(dataset['extras'][name])[clustered].ravel()
            values=values[np.isfinite(values)]
            low=1. if name=='elongation' else 0.
            high=float(values.max()) if len(values) else low+1.
            high=high+.05*(high-low) if high>low else low+1.
            limits=(low,high)
        if limits is not None:
            limits=np.asarray(limits,dtype=float)
            if limits.shape!=(2,) or not np.isfinite(limits).all() or limits[1]<=limits[0]:
                raise ValueError(f'Invalid histogram_xlim for {name}: {limits}')
            bins=10 if name in ('DSI','OSI') else int(count)
            specifications[name]=(tuple(limits),np.linspace(*limits,bins+1))
        else:
            specifications[name]=(None,int(count))
    return specifications


